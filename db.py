# ---------------------------------------------------------------- Postgres (produção: Vercel + Neon)
# Com a variável DATABASE_URL definida, o app usa Postgres; sem ela, SQLite em instance/app.db.
# O código do app continua escrevendo SQL no estilo SQLite (placeholders "?", INSERT OR REPLACE, lastrowid);
# a classe ConexaoPG traduz isso para o Postgres.

def _schema_pg(schema):
    s = schema.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    s = s.replace(" COLLATE NOCASE", "")  # o app já guarda e-mails em minúsculas
    s = s.replace("BLOB", "BYTEA").replace("REAL", "DOUBLE PRECISION").replace("INTEGER", "BIGINT")
    return s.replace("(datetime('now'))", "(to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))")


SCHEMA_PG = _schema_pg(SCHEMA)

# chave de cada tabela usada com INSERT OR REPLACE / OR IGNORE
_CHAVES = {"meta": ("chave",), "indice_tr": ("data",), "ajustes_parcela": ("financiamento_id", "numero")}
_COM_ID = ("usuarios", "financiamentos", "amortizacoes")  # INSERTs que devolvem lastrowid
_RE_INSERT = re.compile(r"^\s*INSERT\s+(OR\s+(REPLACE|IGNORE)\s+)?INTO\s+(\w+)\s*\(([^)]*)\)", re.I | re.S)


def traduzir_sql(sql, retornar_id=True):
    """SQL no estilo SQLite -> Postgres. Retorna (sql, devolve_id)."""
    devolve_id = False
    m = _RE_INSERT.match(sql)
    if m:
        modo, tabela = (m.group(2) or "").upper(), m.group(3)
        cols = [c.strip() for c in m.group(4).split(",")]
        sql = sql[:m.start(1)] + sql[m.end(1):] if m.group(1) else sql
        if modo == "REPLACE":
            chave = _CHAVES[tabela]
            sets = ", ".join(f"{c} = EXCLUDED.{c}" for c in cols if c not in chave)
            sql += f" ON CONFLICT ({', '.join(chave)}) " + (f"DO UPDATE SET {sets}" if sets else "DO NOTHING")
        elif modo == "IGNORE":
            sql += " ON CONFLICT DO NOTHING"
        elif retornar_id and tabela in _COM_ID and "RETURNING" not in sql.upper():
            sql += " RETURNING id"
            devolve_id = True
    return sql.replace("?", "%s"), devolve_id


class Linha:
    """Linha de resultado que se comporta como sqlite3.Row: acesso por nome ou posição, dict(linha), desempacotar."""
    __slots__ = ("_cols", "_vals")

    def __init__(self, cols, vals):
        self._cols, self._vals = cols, tuple(bytes(v) if isinstance(v, memoryview) else v for v in vals)

    def __getitem__(self, k):
        return self._vals[self._cols.index(k)] if isinstance(k, str) else self._vals[k]

    def keys(self):
        return list(self._cols)

    def __iter__(self):
        return iter(self._vals)

    def __len__(self):
        return len(self._vals)

    def __eq__(self, outro):
        if isinstance(outro, Linha):
            outro = outro._vals
        return self._vals == tuple(outro) if isinstance(outro, (tuple, list)) else NotImplemented

    __hash__ = None

    def __repr__(self):
        return f"Linha({dict(zip(self._cols, self._vals))})"


def _fabrica_linhas(cursor):
    cols = [d.name for d in cursor.description] if cursor.description else []
    return lambda vals: Linha(cols, vals)


class _CursorPG:
    def __init__(self, cur, lastrowid=None):
        self._cur, self.lastrowid = cur, lastrowid

    def fetchone(self):
        return self._cur.fetchone() if self._cur.description else None

    def fetchall(self):
        return self._cur.fetchall() if self._cur.description else []

    def __iter__(self):
        return iter(self.fetchall())


class ConexaoPG:
    def __init__(self, url):
        import psycopg  # só é necessário em produção
        self._con = psycopg.connect(url, row_factory=_fabrica_linhas, prepare_threshold=None)

    def execute(self, sql, params=()):
        sql, devolve_id = traduzir_sql(sql)
        cur = self._con.cursor()
        cur.execute(sql, tuple(params))
        if devolve_id:
            linha = cur.fetchone()
            return _CursorPG(cur, linha[0] if linha else None)
        return _CursorPG(cur)

    def executemany(self, sql, seq):
        sql, _ = traduzir_sql(sql, retornar_id=False)
        lista = [tuple(p) for p in seq]
        cur = self._con.cursor()
        if lista:
            cur.executemany(sql, lista)
        return _CursorPG(cur)

    def executescript(self, script):
        self._con.execute(script)

    def commit(self):
        self._con.commit()

    def rollback(self):
        self._con.rollback()

    def close(self):
        self._con.close()


def url_postgres():
    # DATABASE_URL (Neon) ou POSTGRES_URL (nome usado por algumas integrações do Vercel)
    return (os.environ.get("DATABASE_URL") or os.environ.get("POSTGRES_URL")
            or current_app.config.get("DATABASE_URL"))


def get_db():
    if "db" not in g:
        url = url_postgres()
        if url:
            g.db = ConexaoPG(url)
        else:
            g.db = sqlite3.connect(current_app.config["DATABASE"])
            g.db.row_factory = sqlite3.Row
            g.db.execute("PRAGMA foreign_keys = ON")
    return g.db


def close_db(_exc=None):
    db = g.pop("db", None)
    if db is not None:
        db.close()


def _colunas(db, tabela):
    return {r[1] for r in db.execute(f"PRAGMA table_info({tabela})")}


def _migrar(db):
    """Atualiza bancos criados por versões anteriores do app."""
    cols = _colunas(db, "usuarios")
    if "username" in cols:
        db.execute("ALTER TABLE usuarios RENAME COLUMN username TO email")
    if "nome" not in cols:
        db.execute("ALTER TABLE usuarios ADD COLUMN nome TEXT NOT NULL DEFAULT ''")
    if "foto" not in cols:
        db.execute("ALTER TABLE usuarios ADD COLUMN foto BLOB")
        db.execute("ALTER TABLE usuarios ADD COLUMN foto_tipo TEXT")
        db.execute("ALTER TABLE usuarios ADD COLUMN foto_versao INTEGER NOT NULL DEFAULT 0")
    cols = _colunas(db, "financiamentos")
    if "prazo_original" not in cols:
        db.execute("ALTER TABLE financiamentos ADD COLUMN prazo_original INTEGER NOT NULL DEFAULT 0")
        db.execute("UPDATE financiamentos SET prazo_original = prazo_meses")
    for col in ("instituicao", "numero_contrato"):
        if col not in cols:
            db.execute(f"ALTER TABLE financiamentos ADD COLUMN {col} TEXT NOT NULL DEFAULT ''")
    for col, padrao in (("indexador", "nenhum"), ("projecao_tr", "media12"), ("tr_assinatura", "")):
        if col not in cols:
            db.execute(f"ALTER TABLE financiamentos ADD COLUMN {col} TEXT NOT NULL DEFAULT '{padrao}'")
    if "ajuste_parcela" not in cols:
        db.execute("ALTER TABLE financiamentos ADD COLUMN ajuste_parcela INTEGER NOT NULL DEFAULT 0")
        db.execute("ALTER TABLE financiamentos ADD COLUMN ajuste_valor REAL NOT NULL DEFAULT 0")
    if "tipo_taxa" not in cols:
        db.execute("ALTER TABLE financiamentos ADD COLUMN taxa_informada REAL NOT NULL DEFAULT 0")
        db.execute("ALTER TABLE financiamentos ADD COLUMN tipo_taxa TEXT NOT NULL DEFAULT ''")
    cols_parcelas = _colunas(db, "parcelas")
    if cols_parcelas and "correcao" not in cols_parcelas:
        db.execute("ALTER TABLE parcelas ADD COLUMN correcao REAL NOT NULL DEFAULT 0")
    db.commit()


def init_db(app):
    with app.app_context():
        db = get_db()
        if url_postgres():
            db.executescript(SCHEMA_PG)  # banco novo: o esquema já é o atual, sem migrações
            db.commit()
            return
        if "usuarios" in {r[0] for r in db.execute("SELECT name FROM sqlite_master WHERE type='table'")}:
            _migrar(db)
        db.executescript(SCHEMA)
        # versão anterior guardava um único ajuste no próprio contrato: passa para ajustes_parcela
        db.execute("INSERT OR IGNORE INTO ajustes_parcela (financiamento_id, numero, valor_parcela) "
                   "SELECT id, ajuste_parcela, ajuste_valor FROM financiamentos WHERE ajuste_parcela > 0")
        db.execute("UPDATE financiamentos SET ajuste_parcela = 0, ajuste_valor = 0 WHERE ajuste_parcela > 0")
        db.commit()
